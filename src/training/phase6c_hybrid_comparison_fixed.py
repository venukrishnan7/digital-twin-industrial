"""
Phase 6C — compare a factory-specific Random Forest with a rule-override hybrid.

Input:
    factory_phase6_dataset.csv (generated by phase6_factory_rf.py)

Outputs:
    factory_phase6c_hybrid_predictions.csv
    factory_phase6c_hybrid_metrics.txt

This is a synthetic-data research experiment, not a safety-certified controller.
"""
from pathlib import Path

import pandas as pd
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    precision_score,
    recall_score,
    f1_score,
)
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder

SEED = 42
BASE = Path(__file__).resolve().parent
DATA_FILE = BASE / "factory_phase6_dataset.csv"
PRED_FILE = BASE / "factory_phase6c_hybrid_predictions.csv"
REPORT_FILE = BASE / "factory_phase6c_hybrid_metrics.txt"


def metrics_block(name, y_true, y_pred):
    matrix = confusion_matrix(y_true, y_pred, labels=[0, 1])
    report = classification_report(
        y_true,
        y_pred,
        labels=[0, 1],
        target_names=["normal/inactive", "fault active"],
        zero_division=0,
    )
    return (
        f"{name}\n"
        f"  Accuracy:          {accuracy_score(y_true, y_pred):.4f}\n"
        f"  Balanced accuracy: {balanced_accuracy_score(y_true, y_pred):.4f}\n"
        f"  Fault precision:   {precision_score(y_true, y_pred, zero_division=0):.4f}\n"
        f"  Fault recall:      {recall_score(y_true, y_pred, zero_division=0):.4f}\n"
        f"  Fault F1:          {f1_score(y_true, y_pred, zero_division=0):.4f}\n"
        "  Confusion matrix (rows actual [0,1], columns predicted [0,1]):\n"
        f"{matrix}\n\n"
        f"{report}\n"
    )


def main():
    if not DATA_FILE.exists():
        raise FileNotFoundError(
            f"Missing {DATA_FILE.name}. Run phase6_factory_rf.py first."
        )

    df = pd.read_csv(DATA_FILE)
    target = "fault_active_sim"
    required = {
        "run_id",
        target,
        "timing_violation",
        "sensor_timeout",
        "safety_violation",
    }
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Dataset missing required columns: {sorted(missing)}")

    # Exclude rule flags, residuals, IDs and labels from RF input features.
    excluded = {
        "run_id",
        "scenario_label",
        target,
        "fault_type_sim",
        "timing_violation",
        "sensor_timeout",
        "safety_violation",
        "residual_part",
        "residual_clamp",
        "residual_drill_complete",
        "machine_state",
        "prediction_valid",
    }
    feature_cols = [column for column in df.columns if column not in excluded]
    categorical = [column for column in ["state_before"] if column in feature_cols]
    numeric = [column for column in feature_cols if column not in categorical]

    splitter = GroupShuffleSplit(
        n_splits=1,
        test_size=0.25,
        random_state=SEED,
    )
    train_idx, test_idx = next(
        splitter.split(df[feature_cols], df[target], groups=df["run_id"])
    )

    train = df.iloc[train_idx]
    test = df.iloc[test_idx]
    X_train = train[feature_cols]
    X_test = test[feature_cols]
    y_train = train[target].astype(int)
    y_test = test[target].astype(int)

    preprocessor = ColumnTransformer(
        [
            ("categorical", OneHotEncoder(handle_unknown="ignore"), categorical),
            ("numeric", "passthrough", numeric),
        ]
    )
    rf = Pipeline(
        [
            ("preprocessor", preprocessor),
            (
                "classifier",
                RandomForestClassifier(
                    n_estimators=400,
                    class_weight="balanced",
                    min_samples_leaf=2,
                    random_state=SEED,
                    n_jobs=-1,
                ),
            ),
        ]
    )
    rf.fit(X_train, y_train)
    rf_predictions = rf.predict(X_test).astype(int)

    # Offline hybrid comparison: explicit current-row rule triggers cannot be
    # overridden by the RF. This is a research comparison, not machine control.
    rule_trigger = (
        test["timing_violation"].astype(int).to_numpy().astype(bool)
        | test["sensor_timeout"].astype(int).to_numpy().astype(bool)
        | test["safety_violation"].astype(int).to_numpy().astype(bool)
    )
    hybrid_predictions = ((rf_predictions == 1) | rule_trigger).astype(int)

    output = test[["run_id", "cycle", "scenario_label", target]].copy()
    output["rf_predicted_fault"] = rf_predictions
    output["rule_trigger"] = rule_trigger.astype(int)
    output["hybrid_predicted_fault"] = hybrid_predictions
    output.to_csv(PRED_FILE, index=False)

    report_text = (
        "PHASE 6C — RANDOM FOREST VS RULE-OVERRIDE HYBRID\n"
        f"Rows: {len(df)} | independent runs: {df['run_id'].nunique()}\n"
        f"Train: {len(train_idx)} rows / {train['run_id'].nunique()} runs\n"
        f"Test: {len(test_idx)} rows / {test['run_id'].nunique()} runs\n"
        f"Features: {feature_cols}\n"
        "Hybrid policy: predict fault if RF predicts fault OR a current-row timing, "
        "sensor-timeout, or safety rule triggers.\n\n"
        + metrics_block("RANDOM FOREST ONLY", y_test, rf_predictions)
        + metrics_block("HYBRID (RF + RULE OVERRIDE)", y_test, hybrid_predictions)
        + (
            "Caution: labels and rule triggers come from the same simulator. "
            "This measures agreement with simulator-generated labels, not independent "
            "real-world validation. The hybrid is an offline research comparison, "
            "not a controller.\n"
        )
    )
    REPORT_FILE.write_text(report_text, encoding="utf-8")

    print("PHASE 6C — RANDOM FOREST VS RULE-OVERRIDE HYBRID")
    print(f"Rows: {len(df)} | independent runs: {df['run_id'].nunique()}")
    print(f"Train: {len(train_idx)} rows / {train['run_id'].nunique()} runs")
    print(f"Test: {len(test_idx)} rows / {test['run_id'].nunique()} runs")
    print()
    print(metrics_block("RANDOM FOREST ONLY", y_test, rf_predictions))
    print(metrics_block("HYBRID (RF + RULE OVERRIDE)", y_test, hybrid_predictions))
    print(f"Saved predictions: {PRED_FILE}")
    print(f"Saved metrics: {REPORT_FILE}")
    print("NOTE: Synthetic-data research experiment only; not a safety-certified controller.")


if __name__ == "__main__":
    main()
